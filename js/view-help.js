/* =====================================================================
 * js/view-help.js — 使い方・和歌の基礎・制作者（#/help）
 * ---------------------------------------------------------------------
 * 3 ステップの使い方、字余り・字足らず、音数の数え方、和歌の基礎（句切れ・枕詞・掛詞・本歌取り・字余り、例つき）、
 * 読み推定の注意、みんなの和歌（data/site.js の minna.api があるときだけ、DESIGN 14.2）、制作者カード（data/site.js の author）。
 * ===================================================================== */
(function () {
  'use strict';

  var W = window.WAKA = window.WAKA || {};
  var ui = W.ui, el = ui.el;

  function sec(title, children) {
    return el('section', { class: 'doc-sec' }, [el('h2', { class: 'doc-h', text: title })].concat(children));
  }
  function p(t) { return el('p', { text: t }); }

  function moraExample(kana) {
    var n = W.mora.count(kana);
    return el('li', {}, [el('span', { class: 'ex-kana', text: kana }), ' … ' + n + ' 音']);
  }

  function authorCard(site) {
    var a = site.author || {};
    var links = [['X', a.x], ['YouTube', a.youtube], ['BOOTH', a.booth]].filter(function (l) { return l[1]; })
      .map(function (l) { return el('a', { class: 'btn btn-small', href: l[1], target: '_blank', rel: 'noopener', text: l[0] }); });
    return el('div', { class: 'author-card' }, [
      el('div', { class: 'author-mark', 'aria-hidden': 'true', text: (a.name || '和').charAt(0) }),
      el('div', { class: 'author-info' }, [
        el('p', { class: 'author-name', text: a.name || '' }),
        a.role ? el('p', { class: 'muted small', text: a.role }) : null,
        el('div', { class: 'btn-row' }, links)
      ])
    ]);
  }

  /* 和歌の基礎（DESIGN 12-10）: 句切れ・枕詞・掛詞・本歌取り・字余り（＋季節のことば）を 1 か所に。例は著作権の切れた古歌 */
  var BASICS = [
    { term: '句切れ', text: '一首の途中で意味や調子がいったん切れるところ。「〜けり」「〜らし」のような言い切りの形で切れます。切れる位置で「二句切れ」「三句切れ」などと呼びます。',
      ex: '春過ぎて夏来にけらし／白妙の衣干すてふ天の香具山', src: '持統天皇（二句切れ）' },
    { term: '枕詞', text: '決まった言葉の前に置いて調子を整える、主に 5 音の飾りの言葉。意味は訳さないことが多いです。',
      ex: 'ひさかたの光のどけき春の日に', src: '紀友則（「ひさかたの」→ 光）' },
    { term: '掛詞', text: '1 つの音に 2 つの意味を重ねる技。景色と気持ちを同時に言えます。',
      ex: 'わが身世にふるながめせしまに', src: '小野小町（ふる＝降る・経る、ながめ＝長雨・眺め）' },
    { term: '本歌取り', text: '有名な古歌（本歌）の言葉を少し借りて、新しい歌を詠む技。本歌の景色や気持ちが重なって奥行きが出ます。',
      ex: '駒とめて袖うちはらふかげもなし佐野のわたりの雪の夕暮', src: '藤原定家（本歌は万葉集「苦しくも降り来る雨か三輪の崎狭野の渡りに家もあらなくに」）' },
    { term: '字余り', text: '句の音数が 5・7 より多いこと。昔の名歌にもよくあり、「あ・い・う・お」の母音が入る句では自然に読めます。',
      ex: '田子の浦にうち出でてみれば白妙の', src: '山部赤人（第二句「うちいでてみれば」が 8 音）' },
    { term: '季節のことば', text: '「春霞」「時鳥」「紅葉」「初雪」のように、季節を感じさせる景物。和歌は四季と恋が二本の柱です。',
      ex: '', src: '' }
  ];
  function basics() {
    return el('section', { class: 'doc-sec basics', id: 'basics' }, [
      el('h2', { class: 'doc-h', text: '和歌の基礎' }),
      p('知っておくと、歌を読むのも詠むのも楽しくなる 6 つのことば。'),
      el('dl', { class: 'terms basics-list' }, BASICS.reduce(function (out, b) {
        out.push(el('dt', { text: b.term }));
        out.push(el('dd', {}, [
          el('p', { text: b.text }),
          b.ex ? el('p', { class: 'basics-ex' }, [el('span', { class: 'ex-label', text: '例' }), el('span', { class: 'ex-poem', lang: 'ja', text: b.ex }), el('span', { class: 'ex-src', text: '— ' + b.src })]) : null
        ]));
        return out;
      }, [])),
      p('じっくりモードの「歌ことば」パネルから語を選ぶと、いま選んでいる句の末尾に入ります。')
    ]);
  }

  function render(container) {
    var site = W.site || {};
    container.innerHTML = '';
    container.appendChild(el('section', { class: 'view view-doc' }, [
      el('div', { class: 'view-head' }, [
        el('h1', { class: 'view-title', text: '使い方' }),
        el('p', { class: 'lead', text: site.description || '' })
      ]),
      sec('かんたん：えらぶだけで一首', [
        el('ol', { class: 'steps' }, [
          el('li', {}, [el('strong', { text: '4 つの質問に答える' }), ' — 「いつ？」「何を見た・思った？」「どんな気持ち？」「どんなことばで？」を 1 つずつえらびます。えらぶと自動で次の質問へ進み、上の「1 いつ・2 題材・3 気持ち・4 ことば」をタップすると選び直せます。題材はグループごとにたたんであり、上の欄で「さくら」「月」のように探せます。']),
          el('li', {}, [el('strong', { text: '候補からえらぶ' }), ' — 「一首つくる」でできた 3 首を見くらべて「これにする」。スマホでは左右にスワイプして 1 首ずつ見られます。気に入らなければ「ほかの候補」、条件を変えたいときは「条件を変える」。']),
          el('li', {}, [el('strong', { text: '仕上げて できた！' }), ' — 句をタップすると「ほかの言い方」（意味つき）に替えたり、「自分の言葉で書く」で書きかえたりできます。「できた！」で画像になり、「画像を保存」すると作品帳にも自動で入ります。'])
        ]),
        el('p', { class: 'small' }, '「ことば」は 2 つから選べます。「古風なことばで」は「かをり」「けり」など、むかしの和歌のことばだけで詠みます。「現代のことばも混ぜて」は、ふだんの言いまわしの句も入ります。現代のことばも を選ぶと読みは現代かなづかいになります（候補の画面でも「古風」「現代も」を切り替えられます）。'),
        el('p', { class: 'small' }, '大意は句の意味をつないだおおよその訳です。自由に書き換えられます（「できた！」の画面の「意味・ひとこと」）。'),
        el('p', { class: 'small' }, 'ほかの作り方：「穴埋め」は型の空欄に言葉を入れるだけ（候補 3 首は飛ばして仕上げへ）。「ふだんの言葉から」は「桜がきれいだけど散るのがさみしい」のような一言から題材と気持ちを探します。どちらも最初の質問の上のリンクから選べます。'),
        el('p', { class: 'small' }, [el('a', { href: '#/easy', text: 'かんたんモードをひらく' })])
      ]),
      sec('じっくり：自分で 5 句を書く', [
        el('ol', { class: 'steps' }, [
          el('li', {}, [el('strong', { text: '句を入れる' }), ' — 五・七・五・七・七の 5 つの欄に、思いついた言葉を入れます。「シャッフル」で用意された句を選んでも始められます。']),
          el('li', {}, [el('strong', { text: '読みを確かめる' }), ' — 歌らしい読みを優先して自動で入ります。違っていたら読み欄をひらがなで直してください。音数は読みから数えます。']),
          el('li', {}, [el('strong', { text: 'できた！' }), ' — 縦書きの画像になります。短冊・色紙・横長と、色を選んで保存や X で共有ができます。'])
        ])
      ]),
      sec('字余り・字足らず', [
        p('句の音数が目標より多いと「字余り」、少ないと「字足らず」と表示します。'),
        p('1 音の字余りは昔の名歌にもよくあるので黄色で表示するだけです。2 音以上ずれると赤になりますが、それでも画像にはできます。')
      ]),
      sec('音数の数え方', [
        p('かな 1 文字が 1 音です。ただし小さい「ゃ ゅ ょ ぁ ぃ…」は前の字といっしょに 1 音。「っ」「ん」「ー」はそれぞれ 1 音です。'),
        el('ul', { class: 'examples' }, ['きょう', 'ちょっと', 'さんぽ', 'ながながしよを'].map(moraExample)),
        p('読みに漢字が残っていると数えられないので「？」になります。')
      ]),
      basics(),
      sec('読みの自動推定について', [
        p('歌らしい読みを優先しますが、違っていたら読み欄を直してください。'),
        p('「夜（よ）」「今日（けふ）」「紅葉（もみぢ）」のような和歌の読みや、歌ことば辞典にある語はその読みを使い、それ以外は現代語の辞書（kuromoji.js）で推定します。そのため、古語が現代の読み方になることがあります。'),
        p('読み欄はいつでも手で直せます。手で直した句は、本文を変えるまで自動で上書きしません。通信できないときは、読みをひらがなで入れてください。')
      ]),
      W.minna && W.minna.enabled && W.minna.enabled() ? sec('みんなの和歌', [
        p('「できた！」の画面の「みんなの和歌に投稿」を押すと、その歌が「みんな」のページに並び、誰でも見られるようになります。投稿のときに名前（雅号）を入れられます（任意。空なら「詠み人知らず」）。名前以外の個人情報は送りません。大意（意味・ひとこと）も一緒に出ます。今日のお題から作った歌には「今日のお題」の印が付きます。'),
        p('取り下げるときは、投稿したのと同じ端末・ブラウザで「みんな」を開き、自分の歌の「取り下げる」を 2 回押します。'),
        p('ほかの人の歌は「画像にする」で短冊・色紙の画像にして保存・共有でき（雅号と落款は詠んだ人のもの）、「自分の作品帳に写す」で作品帳にも入れられます。「なぞる」はその歌を下書きにしてじっくりモードで書きかえます。'),
        el('p', { class: 'small' }, [el('a', { href: '#/minna', text: 'みんなの和歌をひらく' }), '　', el('a', { href: '#/terms', text: '投稿のきまり（利用規約）' })])
      ]) : null,
      sec('作った歌の保存', [
        p('作品帳と下書きは、この端末のブラウザの中だけに保存されます。ブラウザのデータを消すと作品帳も消えるので、大事な歌は「書き出し (JSON)」や画像で残してください。')
      ]),
      sec('つくった人', [authorCard(site)]),
      el('p', { class: 'small muted' }, [el('a', { href: '#/terms', text: '利用規約・プライバシー' })])
    ]));
  }

  W.views = W.views || {};
  W.views.help = { title: '使い方', render: render };
})();
